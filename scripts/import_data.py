#!/usr/bin/env python3
"""Import a pinned DST snapshot. Lua executes in a restricted, offline environment.

Only constants, declarative recipes, and the autogenerated scrapbook are evaluated.
The sandbox exposes no io/os/package/debug/Python facilities or arbitrary require.
Game entity callbacks are retained as values, never invoked.
"""
