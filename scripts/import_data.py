def extract():
    sandbox = Sandbox()
    sandbox.require("constants")
    # Tile IDs normally come from the engine. Fish school location tables only
    # need stable keys; none of these keys affect food values or recipe tests.
    sandbox.run('setmetatable(WORLD_TILES, {__index=function(_,key) return GROUND[key] or key end})')
    sandbox.require("tuning")
    strings = (CACHE / "strings.lua").read_text()
    names = plain(sandbox.run("return " + lua_table_block(strings, "NAMES"), "names"))
    descriptions = plain(sandbox.run("return " + lua_table_block(strings, "RECIPE_DESC"), "recipe_descriptions"))
    effects = {}
    for key, literal in re.findall(r'(FOOD_EFFECTS_[A-Z_]+)\s*=\s*("(?:[^"\\]|\\.)*")', strings):
        effects[key] = sandbox.run("return " + literal)
    sandbox.env.STRINGS = sandbox.lua.table_from({"NAMES": sandbox.lua.table_from(names), "UI": sandbox.lua.table_from({"COOKBOOK": sandbox.lua.table_from(effects), "CRAFTING_STATION_FILTERS": sandbox.lua.table()})})
    sandbox.env.STRINGS["WET_PREFIX"] = sandbox.run("return " + lua_table_block(strings, "WET_PREFIX"))
    scrapbook = plain(sandbox.run((CACHE / "screens/redux/scrapbookdata.lua").read_text(), "scrapbook"))
    cooking = sandbox.require("cooking")
    ingredients = {k: plain(v["tags"]) for k, v in cooking["ingredients"].items()}

    # Every function must be a single pure return expression or the import fails.
    rules, recipe_meta = {}, {}
    for module in ["preparedfoods", "preparedfoods_warly", "preparednonfoods"]:
        source = (CACHE / (module + ".lua")).read_text()
        for rid, value in sandbox.require(module).items():
            body = lua_table_block(source, rid)
            test = re.search(r"test\s*=\s*function\s*\([^)]*\)\s*return\s+(.*?)\s*end\s*,", body, re.S)
            if not test:
                raise ValueError(f"Unsupported recipe test: {rid}")
            expression = test.group(1).strip()
            rules[rid] = RuleParser(expression).complete()
            recipe_meta[rid] = {"source": module + ".lua", "line": source[:source.index(body)].count("\n") + 1, "expression": expression}

    sandbox.run(CAPTURE_RECIPES, "capture_recipes")
    sandbox.require("recipes")
    raw_crafts = plain(sandbox.env.AllRecipes)
    filters = plain(sandbox.env.CRAFTING_FILTERS)
    categories = {}
    for key, value in filters.items():
        if isinstance(value.get("recipes"), list):
            for rid in value["recipes"]:
                categories.setdefault(rid, []).append(key)

    item_ids = set(scrapbook)
    item_ids.update(ACTUAL.get(k, k) for k in ingredients if ACTUAL.get(k, k) in scrapbook)
    for r in raw_crafts.values():
        item_ids.add(r["product"])
        item_ids.update(i["item"] for i in r["ingredients"])

    def display(key):
        entry = scrapbook.get(key, {})
        return names.get(str(entry.get("name", key)).upper(), names.get(key.upper(), key.replace("_", " ").title()))

    items = {}
    for key in sorted(item_ids):
        entry = scrapbook.get(key, {})
        items[key] = {"id": key, "name": display(key), "kind": entry.get("type", "item"), "subtype": entry.get("subcat"), "icon": key, "character": entry.get("craftingprefab")}
        if descriptions.get(key.upper()):
            items[key]["description"] = descriptions[key.upper()]
    foods = {}
    for key, entry in scrapbook.items():
        if "hungervalue" not in entry:
            continue
        # Scrapbook contains the standard survival world's edible entities, not
        # the single-player/DLC or separate Forge/Gorge food tables.
        foods[key] = {"id": key, "hunger": entry["hungervalue"], "sanity": entry.get("sanityvalue", 0), "health": entry.get("healthvalue", 0), "diet": entry.get("foodtype", "GENERIC").lower(), "perish": entry.get("perishable"), "method": "raw"}
        if key.endswith("_dried"):
            foods[key]["method"] = "dried"
        elif key.endswith("_cooked") or key in ALIASES or key == "cookedmandrake":
            foods[key]["method"] = "roasted"
        if key.startswith(("winter_food", "wintersfeast", "halloweencandy", "yot", "carnivalfood")):
            foods[key]["event"] = "Seasonal event"
        if entry.get("craftingprefab"):
            foods[key]["character"] = entry["craftingprefab"]
        if foods[key]["diet"] in {"elemental", "wood", "gears", "horrible", "roughage", "lunar_shards", "burnt"}:
            foods[key]["specialDiet"] = True

    recipes = {}
    for rid, ast in rules.items():
        data = cooking["recipes"]["portablecookpot"][rid]
        meta = recipe_meta[rid]
        record = {"id": rid, "rule": ast, "priority": data["priority"] or 0, "weight": data["weight"] or 1,
                  "station": "portablecookpot" if meta["source"] == "preparedfoods_warly.lua" else "cookpot",
                  "cooktime": (data["cooktime"] or 1) * sandbox.env.TUNING["BASE_COOK_TIME"],
                  "yield": data["stacksize"] or 1, "effect": data["oneat_desc"], "source": meta["source"], "line": meta["line"]}
        if data["card_def"] and data["card_def"]["ingredients"]:
            record["example"] = [ACTUAL.get(row[0], row[0]) for row in plain(data["card_def"]["ingredients"]) for _ in range(int(row[1]))]
        recipes[rid] = record
        if rid not in items:
            items[rid] = {"id": rid, "name": display(rid), "kind": "food", "icon": rid}
        if rid not in foods and meta["source"] != "preparednonfoods.lua":
            foods[rid] = {"id": rid, "hunger": data["hunger"] or 0, "sanity": data["sanity"] or 0, "health": data["health"] or 0, "perish": data["perishtime"], "diet": str(data["foodtype"] or "generic").lower()}
        if rid in foods:
            foods[rid].update({"method": "crockpot", "recipe": rid, "effect": record["effect"]})
            if record["station"] == "portablecookpot":
                foods[rid]["character"] = "warly"
            if rid == "jellybean":
                foods[rid]["health"] = data["health"]
                foods[rid]["delayedHealth"] = sandbox.env.TUNING["JELLYBEAN_DURATION"] / sandbox.env.TUNING["JELLYBEAN_TICK_RATE"] * sandbox.env.TUNING["JELLYBEAN_TICK_VALUE"]
                foods[rid]["delayedSeconds"] = sandbox.env.TUNING["JELLYBEAN_DURATION"]

    # Spicing is a documented two-item transform, not a four-slot recipe.
    transforms = []
    for key, entry in scrapbook.items():
        for dep in entry.get("deps", []):
            if dep == ACTUAL.get(key + "_cooked", key + "_cooked") or (key == "mandrake" and dep == "cookedmandrake"):
                transforms.append({"from": key, "to": dep, "method": "Roast", "station": "Fire"})
            elif dep == key + "_dried":
                transforms.append({"from": key, "to": dep, "method": "Dry", "station": "Drying Rack"})
    for rid, data in sandbox.require("spicedfoods").items():
        base = data["basename"]
        spice = str(data["spice"]).lower()
        if base not in foods:
            continue
        foods[rid] = {**foods[base], "id": rid, "method": "seasoned", "base": base, "spice": spice, "character": "warly"}
        del foods[rid]["recipe"]
        flavor = {"spice_garlic": "Garlic", "spice_sugar": "Honey", "spice_chili": "Chili", "spice_salt": "Salt"}[spice]
        items[rid] = {"id": rid, "name": f'{flavor} {items[base]["name"]}', "kind": "food", "icon": base, "character": "warly"}
        transforms.append({"from": base, "to": rid, "method": "Season", "station": "Seasoning Station", "extra": spice, "character": "warly"})
        transforms.append({"from": spice, "to": rid, "method": "Season", "station": "Seasoning Station", "extra": base, "character": "warly"})

    crafts = []
    fields = ["builder_tag", "builder_skill", "nounlock", "manufactured", "hint_msg", "actionstr", "placementRestricted", "dynamicYield", "canbuild", "limitedamount", "no_deconstruction"]
    for rid, r in sorted(raw_crafts.items()):
        record = {k: r[k] for k in fields if k in r and r[k] not in (False, None)}
        record.update({"id": rid, "product": r["product"], "ingredients": r["ingredients"] or [], "yield": r["yield"], "tech": r["tech"], "categories": categories.get(rid, []), "structure": bool(r.get("placer"))})
        if r["tech"].startswith(("YOT", "CARNIVAL", "MADSCIENCE", "WINTERSFEAST")):
            record["event"] = r["tech"]
        crafts.append(record)
        if r["product"] in foods and foods[r["product"]]["method"] == "raw":
            foods[r["product"]]["method"] = "crafted"
    construction = plain(sandbox.env.CONSTRUCTION_PLANS)
    # Most construction plans are successive projects, not alternative recipes.
    # Preserve them separately; they are labelled as construction in the UI.
    construction = {k: v for k, v in construction.items() if isinstance(v, list)}
    return sandbox, cooking, scrapbook, {"items": items, "foods": foods, "recipes": recipes, "ingredients": ingredients, "aliases": ALIASES, "transforms": transforms, "crafts": crafts, "construction": construction}


def build_uses(sandbox, cooking, scrapbook, data):
    """Exhaust all four-slot multisets over semantically distinct ingredients.

    Ingredients are equivalent only if their entire referenced tag vector and
    every named-recipe identity agree. This is exhaustive, not a filler heuristic.
    Store one verified witness per ingredient class and resulting dish, per pot.
    """
    name_refs, tag_refs = set(), set()

    def refs(node):
        if node[0] == "ref":
            (name_refs if node[1] == "names" else tag_refs).add(node[2])
        for child in node[1:]:
            if isinstance(child, list):
                refs(child)
    for r in data["recipes"].values():
        refs(r["rule"])
    classes = {}
    preferred = ["berries", "ice", "twigs", "carrot", "meat", "smallmeat", "monstermeat", "bird_egg", "honey", "fishmeat", "kelp", "tomato", "corn", "potato"]
    priority = {key: i for i, key in enumerate(preferred)}
    for key, tags in data["ingredients"].items():
        actual = ACTUAL.get(key, key)
        if actual not in scrapbook:
            continue
        signature = json.dumps([key if key in name_refs else None, [(tag, tags.get(tag, 0)) for tag in sorted(tag_refs)]])
        classes.setdefault(signature, []).append(key)
    groups = []
    for group in classes.values():
        group.sort(key=lambda key: (priority.get(ACTUAL.get(key, key), 100), "_cooked" in key or "_dried" in key, key))
        groups.append(group)
    groups.sort(key=lambda group: (priority.get(ACTUAL.get(group[0], group[0]), 100), group[0]))
    reps = [group[0] for group in groups]
    sandbox.env.IMPORT_REPS = sandbox.lua.table_from(reps)
    sandbox.env.IMPORT_RECIPES = cooking["recipes"]
    sandbox.env.IMPORT_INGREDIENTS = cooking["ingredients"]
    count = len(reps)
    print(f"Enumerating {count} ingredient classes; {count*(count+1)*(count+2)*(count+3)//24:,} four-slot multisets", flush=True)
    results = sandbox.run('''
        local reps=IMPORT_REPS
        local ingredients=IMPORT_INGREDIENTS
        local pots={"cookpot","portablecookpot"}
        local recipes={}
        for _,pot in ipairs(pots) do
            recipes[pot]={}
            for _,r in pairs(IMPORT_RECIPES[pot]) do recipes[pot][#recipes[pot]+1]=r end
            table.sort(recipes[pot],function(a,b) if a.priority==b.priority then return a.name<b.name end return a.priority>b.priority end)
        end
        local uses={cookpot={},portablecookpot={}}
        local function evaluate(pot,names,tags,combo)
            local winners={}; local top=nil
            for _,r in ipairs(recipes[pot]) do
                if top and r.priority<top then break end
                if r.test(pot,names,tags) then
                    top=r.priority; winners[#winners+1]=r.name
                end
            end
            for _,idx in ipairs(combo) do
                local key=reps[idx]
                uses[pot][key]=uses[pot][key] or {}
                for _,rid in ipairs(winners) do
                    local old=uses[pot][key][rid]
                    if old==nil or (#old.winners>1 and #winners==1) then
                        uses[pot][key][rid]={combo={reps[combo[1]],reps[combo[2]],reps[combo[3]],reps[combo[4]]},winners=winners}
                    end
                end
            end
        end
        local tags={}; local names={}
        local function add(key,delta)
            local n=(names[key] or 0)+delta
            names[key]=n~=0 and n or nil
            for tag,value in pairs(ingredients[key].tags) do
                local sum=(tags[tag] or 0)+value*delta
                tags[tag]=sum~=0 and sum or nil
            end
        end
        for a=1,#reps do
            add(reps[a],1)
            for b=a,#reps do
                add(reps[b],1)
                for c=b,#reps do
                    add(reps[c],1)
                    for d=c,#reps do
                        add(reps[d],1)
                        local combo={a,b,c,d}
                        evaluate("cookpot",names,tags,combo)
                        evaluate("portablecookpot",names,tags,combo)
                        add(reps[d],-1)
                    end
                    add(reps[c],-1)
                end
                add(reps[b],-1)
            end
            add(reps[a],-1)
        end
        return uses
    ''', "exhaustive_uses")
    compact = {}
    for pot, values in plain(results).items():
        compact[pot] = {}
        for group in groups:
            representative = group[0]
            for member in group:
                actual = ACTUAL.get(member, member)
                entries = {}
                for rid, witness in values.get(representative, {}).items():
                    combo = list(witness["combo"])
                    combo[combo.index(representative)] = member
                    entries[rid] = {"combo": [ACTUAL.get(k, k) for k in combo], "winners": witness["winners"]}
                compact[pot][actual] = entries
    return compact, {"ingredientClasses": count, "multisets": count*(count+1)*(count+2)*(count+3)//24}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--skip-uses", action="store_true", help="Import metadata without recomputing use witnesses")
    args = parser.parse_args()
    CACHE.mkdir(parents=True, exist_ok=True)
    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
        hashes = dict(pool.map(fetch, FILES))
    sandbox, cooking, scrapbook, data = extract()
    previous_report = ROOT / "data/import-report.json"
    previous = json.loads(previous_report.read_text()) if args.skip_uses and previous_report.exists() else {}
    if args.skip_uses and previous and previous.get("revision") != LOCK["revision"]:
        raise ValueError("The source revision changed. Run the full importer to recompute recipe uses.")
    stats = {key: previous[key] for key in ["ingredientClasses", "multisets"] if key in previous}
    output = ROOT / "public/data"
    output.mkdir(parents=True, exist_ok=True)
    if not args.skip_uses:
        uses, stats = build_uses(sandbox, cooking, scrapbook, data)
        (output / "uses.json").write_text(json.dumps(uses, separators=(",", ":"), sort_keys=True) + "\n")
