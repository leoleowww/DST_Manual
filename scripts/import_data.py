ACTUAL = {v: k for k, v in ALIASES.items()}


def fetch(name):
    target = CACHE / name
    if not target.exists():
        url = f'https://raw.githubusercontent.com/{LOCK["repository"]}/{LOCK["revision"]}/{name}'
        request = urllib.request.Request(url, headers={"User-Agent": "DST-Field-Guide-Importer"})
        content = urllib.request.urlopen(request, timeout=60).read()
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    return name, hashlib.sha256(target.read_bytes()).hexdigest()


def lua_table_block(source, key):
    """Read one named table, respecting quoted strings and Lua comments."""
    match = re.search(r"(?m)^\s*" + re.escape(key) + r"\s*=\s*\{", source)
    if not match:
        raise ValueError(f"Missing table: {key}")
    start = source.index("{", match.start())
    depth, i = 0, start
    while i < len(source):
        if source.startswith("--[[", i):
            i = source.index("]]", i + 4) + 2
            continue
        if source.startswith("--", i):
            pos = source.find("\n", i)
            i = len(source) if pos == -1 else pos + 1
            continue
        char = source[i]
        if char in "\"'":
            quote = char
            i += 1
            while i < len(source) and source[i] != quote:
                i += 2 if source[i] == "\\" else 1
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if not depth:
                return source[start:i + 1]
        i += 1
    raise ValueError(f"Unclosed table: {key}")


def deny_python_attributes(obj, attribute, is_setting):
    raise AttributeError("Python attributes are not available in the Lua data sandbox")


class Sandbox:
    def __init__(self):
        self.lua = LuaRuntime(unpack_returned_tuples=True, register_eval=False, register_builtins=False, attribute_filter=deny_python_attributes)
        self.env = self.lua.eval('''function()
            local e={assert=assert,error=error,ipairs=ipairs,next=next,pairs=pairs,pcall=pcall,
                select=select,tonumber=tonumber,tostring=tostring,type=type,unpack=table.unpack,
                setmetatable=setmetatable,getmetatable=getmetatable,rawset=rawset,rawget=rawget,
                math=math,string=string,table=table,BRANCH="release"}
            e._G=e
            e.CLOTHING={}; e.BEEFALO_CLOTHING={}; e.MISC_ITEMS={}
            e.IsConsole=function() return false end
            e.IsPS4=e.IsConsole; e.IsXB1=e.IsConsole; e.IsSwitch=e.IsConsole
            e.math.pow=function(x,y) return x^y end
            e.table.invert=function(t) local r={} for k,v in pairs(t) do r[v]=k end return r end
            e.table.count=function(t) local n=0 for _ in pairs(t) do n=n+1 end return n end
            e.table.contains=function(t,x) for _,v in pairs(t) do if v==x then return true end end return false end
            e.shallowcopy=function(t) local r={} for k,v in pairs(t) do r[k]=v end return r end
            e.deepcopy=function(t) if type(t)~="table" then return t end local r={} for k,v in pairs(t) do r[k]=e.deepcopy(v) end return r end
            e.ArrayUnion=function(a,b) local r={} for _,v in ipairs(a) do r[#r+1]=v end for _,v in ipairs(b) do r[#r+1]=v end return r end
            e.Point=function(x,y,z) return {x=x,y=y,z=z} end
            e.Vector3=e.Point
            return e
        end''')()
        self.loader = self.lua.eval('function(s,n,e) return assert(load(s,n,"t",e))() end')
        self.modules = {}
        self.env.require = self.require

    def run(self, source, name="import"):
        return self.loader(source, name, self.env)

    def require(self, name):
        # Cosmetic registries and the engine's Recipe class are unnecessary for
        # nutrition and ingredient data. Recipe constructors are captured below.
        if name in {"util", "prefabskins", "clothing", "beefalo_clothing", "misc_items",
                    "emote_items", "idleanimations_items", "item_blacklist", "entitlementlookups", "recipe"}:
            return self.lua.table()
        if name in self.modules:
            return self.modules[name]
        path = name + ".lua"
        if path not in FILES:
            raise ValueError(f"Module not permitted in importer: {name}")
        self.modules[name] = self.run((CACHE / path).read_text(), name)
        return self.modules[name]


def plain(value):
    if lua_type(value) == "table":
        keys = list(value.keys())
        if keys and set(keys) == set(range(1, len(keys) + 1)):
            return [plain(value[i]) for i in range(1, len(keys) + 1)]
        return {str(k): plain(v) for k, v in value.items() if lua_type(v) != "function"}
    if lua_type(value) == "function":
        return None
    return value


class RuleParser:
    """A small, fail-closed parser for the game's pure recipe expressions.

    Export an AST instead of shipping eval() or executable Lua to the browser.
    Lua and/or return operands and zero is truthy; the JS evaluator preserves it.
    """
    PRECEDENCE = {"or": 1, "and": 2, "==": 3, "~=": 3, ">=": 3, "<=": 3, ">": 3, "<": 3, "+": 4, "-": 4, "*": 5, "/": 5}

    def __init__(self, expression):
        expression = re.sub(r"--[^\n]*", "", expression)
        pattern = r'\s*(>=|<=|==|~=|[()+*/<>-]|\+|(?:names|tags)\.[a-zA-Z_0-9]+|\d+(?:\.\d*)?|\.\d+|\b(?:and|or|not|true|false|nil|cooker)\b|"[^"\\]*(?:\\.[^"\\]*)*"|\'[^\'\\]*(?:\\.[^\'\\]*)*\')'
        self.tokens = []
        pos = 0
        while pos < len(expression.strip()):
            match = re.compile(pattern).match(expression, pos)
            if not match:
                raise ValueError(f"Unsupported recipe expression near {expression[pos:]}")
            self.tokens.append(match.group(1))
            pos = match.end()
        self.index = 0

    def parse(self, minimum=0):
        token = self.tokens[self.index]
        self.index += 1
        if token in ("not", "-"):
            left = ["not" if token == "not" else "neg", self.parse(6)]
        elif token == "(":
            left = self.parse()
            if self.tokens[self.index] != ")":
                raise ValueError("Unclosed expression")
            self.index += 1
        elif token.startswith(("names.", "tags.")):
            group, key = token.split(".")
            left = ["ref", group, key]
        elif token == "cooker":
            left = ["cooker"]
        elif token in ("true", "false", "nil"):
            left = ["literal", {"true": True, "false": False, "nil": None}[token]]
        elif token[0] in "\"'":
            left = ["literal", token[1:-1]]
        else:
            left = ["literal", float(token)]
        while self.index < len(self.tokens):
            op = self.tokens[self.index]
            level = self.PRECEDENCE.get(op, -1)
            if level < minimum:
                break
            self.index += 1
            left = [op, left, self.parse(level + 1)]
        return left

    def complete(self):
        value = self.parse()
        if self.index != len(self.tokens):
            raise ValueError("Unconsumed recipe expression")
        return value


